def ranges(predicate):
    points = [n for n in range(0x110000) if predicate(chr(n))]
    spans = []
    for n in points:
        if spans and spans[-1][1] + 1 == n:
            spans[-1][1] = n
        else:
            spans.append([n, n])
    return [f"\\x{{{a:x}}}" + (f"-\\x{{{b:x}}}" if a != b else "") for a, b in spans]


